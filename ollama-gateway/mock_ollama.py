"""A stand-in for Ollama so the gateway can be demoed on any laptop.

It answers a subset of Ollama's real API with the same JSON shapes
(/api/tags, /api/version, /api/ps, /api/show, /api/chat, /api/generate,
/api/pull, /api/delete, /v1/models, /v1/chat/completions). Responses are
canned text streamed word by word. If real Ollama is installed, skip this
file and point the gateway at it with OLLAMA_URL.

    python mock_ollama.py            # listens on 127.0.0.1:11434
"""
from __future__ import annotations

import asyncio
import json
import time

from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse, StreamingResponse

GB = 1024 ** 3
MODELS = {
    "llama3.2:latest": {"size": int(2.0 * GB), "family": "llama", "params": "3.2B", "quant": "Q4_K_M"},
    "qwen3:8b": {"size": int(5.2 * GB), "family": "qwen3", "params": "8.2B", "quant": "Q4_K_M"},
    "gemma3:12b": {"size": int(8.1 * GB), "family": "gemma3", "params": "12.2B", "quant": "Q4_K_M"},
    "deepseek-r1:14b": {"size": int(9.0 * GB), "family": "qwen2", "params": "14.8B", "quant": "Q4_K_M"},
    "nomic-embed-text:latest": {"size": int(0.27 * GB), "family": "nomic-bert", "params": "137M", "quant": "F16"},
}

app = FastAPI(title="mock-ollama")


def tag(name: str) -> str:
    return name if ":" in name else name + ":latest"


def entry(name: str) -> dict:
    m = MODELS[name]
    return {"name": name, "model": name, "modified_at": "2026-09-28T10:00:00Z", "size": m["size"],
            "digest": f"sha256:{abs(hash(name)):064x}"[:71],
            "details": {"format": "gguf", "family": m["family"], "parameter_size": m["params"],
                        "quantization_level": m["quant"]}}


def reply_for(prompt: str, model: str) -> str:
    return (f"(mock {model}) You asked: \"{prompt[:80]}\". In a real deployment this answer would "
            f"be generated by the model on the GPU; the gateway only checked that you may use {model}.")


@app.get("/")
def root():
    return "Ollama is running"


@app.get("/api/version")
def version():
    return {"version": "0.21.0-mock"}


@app.get("/api/tags")
def tags():
    return {"models": [entry(n) for n in MODELS]}


@app.get("/v1/models")
def v1_models():
    return {"object": "list", "data": [{"id": n, "object": "model", "created": 1759000000, "owned_by": "library"} for n in MODELS]}


@app.get("/api/ps")
def ps():
    return {"models": [{**entry("llama3.2:latest"), "expires_at": "2026-10-04T18:00:00Z", "size_vram": MODELS["llama3.2:latest"]["size"]}]}


@app.post("/api/show")
async def show(request: Request):
    body = await request.json()
    name = tag(body.get("model") or body.get("name", ""))
    if name not in MODELS:
        return JSONResponse({"error": f"model '{name}' not found"}, status_code=404)
    return {"modelfile": f"FROM {name}", "details": entry(name)["details"], "capabilities": ["completion"]}


async def _stream(model: str, text: str, chat: bool):
    started = time.time()
    for word in text.split(" "):
        await asyncio.sleep(0.03)
        piece = word + " "
        obj = {"model": model, "created_at": "2026-10-04T15:00:00Z", "done": False}
        obj.update({"message": {"role": "assistant", "content": piece}} if chat else {"response": piece})
        yield json.dumps(obj) + "\n"
    final = {"model": model, "done": True, "done_reason": "stop", "total_duration": int((time.time() - started) * 1e9),
             "eval_count": len(text.split(" ")), "prompt_eval_count": 12}
    final.update({"message": {"role": "assistant", "content": ""}} if chat else {"response": ""})
    yield json.dumps(final) + "\n"


@app.post("/api/chat")
async def chat(request: Request):
    body = await request.json()
    model = tag(body.get("model", ""))
    if model not in MODELS:
        return JSONResponse({"error": f"model '{model}' not found, try pulling it first"}, status_code=404)
    prompt = (body.get("messages") or [{}])[-1].get("content", "")
    text = reply_for(prompt, model)
    if body.get("stream", True):
        return StreamingResponse(_stream(model, text, True), media_type="application/x-ndjson")
    return {"model": model, "message": {"role": "assistant", "content": text}, "done": True}


@app.post("/api/generate")
async def generate(request: Request):
    body = await request.json()
    model = tag(body.get("model", ""))
    if model not in MODELS:
        return JSONResponse({"error": f"model '{model}' not found, try pulling it first"}, status_code=404)
    text = reply_for(body.get("prompt", ""), model)
    if body.get("stream", True):
        return StreamingResponse(_stream(model, text, False), media_type="application/x-ndjson")
    return {"model": model, "response": text, "done": True}


@app.post("/v1/chat/completions")
async def openai_chat(request: Request):
    body = await request.json()
    model = tag(body.get("model", ""))
    prompt = (body.get("messages") or [{}])[-1].get("content", "")
    return {"id": "chatcmpl-mock", "object": "chat.completion", "model": model,
            "choices": [{"index": 0, "message": {"role": "assistant", "content": reply_for(prompt, model)},
                         "finish_reason": "stop"}]}


@app.post("/api/pull")
async def pull(request: Request):
    body = await request.json()
    name = tag(body.get("model") or body.get("name", ""))

    async def progress():
        yield json.dumps({"status": "pulling manifest"}) + "\n"
        for pct in (25, 50, 75, 100):
            await asyncio.sleep(0.1)
            yield json.dumps({"status": "downloading", "total": 100, "completed": pct}) + "\n"
        MODELS.setdefault(name, {"size": int(1.5 * GB), "family": "unknown", "params": "?", "quant": "Q4_K_M"})
        yield json.dumps({"status": "success"}) + "\n"
    return StreamingResponse(progress(), media_type="application/x-ndjson")


@app.delete("/api/delete")
async def delete(request: Request):
    body = await request.json()
    name = tag(body.get("model") or body.get("name", ""))
    if MODELS.pop(name, None) is None:
        return JSONResponse({"error": f"model '{name}' not found"}, status_code=404)
    return JSONResponse({})


if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="127.0.0.1", port=11434, log_level="warning")
